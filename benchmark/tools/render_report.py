#!/usr/bin/env python3
"""render RESULTS.md and every experiment table.md from results.json files.

stdlib only. reads benchmark/experiments/NN-slug/results.json plus the
hypothesis / method / verdict lines of each experiment README.md, and
writes:
  RESULTS.md                                 (one section per experiment)
  benchmark/experiments/NN-slug/table.md     (that experiment's tables)

results.json contract:
  {
    "experiment": "NN-slug", "title": "...",
    "provenance": {"status": "measured"|"transcribed", "source": "...", "date": "...", "notes": "..."},
    "constants": {"source_bytes": 3975063106, ...},          optional, row-level fallback values
    "tables": [{"title": "...", "columns": [...], "rows": [{...}], "notes": ["..."]}],
    "notes": ["..."]                                          optional, after the tables
  }
column spec: {"key", "label", "fmt", "from", "num", "den"}; fmt is one of
  str (default), int, f1..f9, mb (bytes/1e6, 1 decimal), gb (bytes/1e9, 3 decimals),
  ratio (num/den, 2 decimals + x), pct_change ((num/den - 1) * 100, signed, 1 decimal).
"from" renders another key through fmt; "num"/"den" name row keys or constants.
bytes are stored as integers; MB and GB exist only at render time.

usage (repo root): python3 benchmark/tools/render_report.py [--check]
--check renders in memory and exits 1 when any output on disk is stale (ci gate).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _bench_env as env  # noqa: E402

RESULTS_MD = env.REPO / "RESULTS.md"
README_KEYS = ("hypothesis", "method", "verdict")
SECTION_RE = re.compile(r"^(\d+)-(.+)$")

HEADER = """# mtg card corpus benchmark: results

generated by `benchmark/tools/render_report.py` from `benchmark/experiments/*/results.json`
and the hypothesis / method / verdict lines of each experiment `README.md`.
do not edit by hand: change the json or the readme and rerun
`python3 benchmark/tools/render_report.py` (`--check` is the ci gate).

units: bytes are stored exact; MB = bytes / 1e6 and GB = bytes / 1e9 (decimal, never MiB or GiB).
full-corpus rows carry two ratios against the 3975063106-byte jpeg source (38627 cards, normal/front):
ratio_urna = source_bytes / urna_bytes (the whole self-contained file) and
ratio_media = source_bytes / media_bytes (the embedded media blob alone).
sample rows use the 211018809-byte source of the 2048-card sample.
every section ends with its provenance: `measured` means the numbers were read from artifacts
or sidecars on disk, `transcribed` means they were copied from a report whose artifacts are gone.
"""


def fmt_value(v, fmt: str) -> str:
    if v is None:
        return "-"
    if fmt == "int":
        return str(int(v))
    if fmt == "mb":
        return f"{v / 1e6:.1f}"
    if fmt == "gb":
        return f"{v / 1e9:.3f}"
    if re.fullmatch(r"f\d", fmt):
        return f"{float(v):.{fmt[1]}f}"
    if isinstance(v, bool):
        return "yes" if v else "no"
    return str(v)


def cell(col: dict, row: dict, constants: dict) -> str:
    fmt = col.get("fmt", "str")

    def lookup(key: str):
        if key in row:
            return row[key]
        return constants.get(key)

    if fmt in ("ratio", "pct_change"):
        num, den = lookup(col["num"]), lookup(col["den"])
        if num is None or den in (None, 0):
            return "-"
        if fmt == "ratio":
            return f"{num / den:.2f}x"
        return f"{(num / den - 1) * 100:+.1f}%"
    return fmt_value(lookup(col.get("from", col["key"])), fmt)


def render_table(table: dict, constants: dict) -> list[str]:
    cols = table["columns"]
    out = []
    if table.get("title"):
        out += [f"### {table['title']}", ""]
    out.append("| " + " | ".join(c["label"] for c in cols) + " |")
    aligns = []
    for c in cols:
        numeric = c.get("fmt", "str") not in ("str",)
        aligns.append("---:" if numeric else "---")
    out.append("| " + " | ".join(aligns) + " |")
    for row in table["rows"]:
        out.append("| " + " | ".join(cell(c, row, constants) for c in cols) + " |")
    out.append("")
    for note in table.get("notes", []):
        out += [f"- {note}"]
    if table.get("notes"):
        out.append("")
    return out


def readme_lines(exp_dir: Path) -> dict[str, str]:
    found = {k: "" for k in README_KEYS}
    readme = exp_dir / "README.md"
    if not readme.is_file():
        return found
    for line in readme.read_text().splitlines():
        for key in README_KEYS:
            if line.lower().startswith(f"{key}:"):
                found[key] = line[len(key) + 1 :].strip()
    return found


def render_section(exp_dir: Path, doc: dict, with_context: bool) -> list[str]:
    m = SECTION_RE.match(exp_dir.name)
    number, slug = (m.group(1), m.group(2)) if m else ("", exp_dir.name)
    constants = doc.get("constants", {})
    out = [f"## {number} {slug}: {doc.get('title', '')}".rstrip(), ""]
    if with_context:
        ctx = readme_lines(exp_dir)
        for key in README_KEYS:
            out.append(f"{key}: {ctx[key] or '(not written yet)'}")
        out.append("")
    for table in doc.get("tables", []):
        out += render_table(table, constants)
    for note in doc.get("notes", []):
        out.append(f"- {note}")
    if doc.get("notes"):
        out.append("")
    p = doc["provenance"]
    line = f"provenance: {p['status']}; source: {p['source']}; date: {p['date']}"
    if p.get("notes"):
        line += f"; notes: {p['notes']}"
    out += [line, ""]
    return out


def experiments() -> list[tuple[Path, dict]]:
    found = []
    for d in sorted(env.EXPERIMENTS.iterdir()):
        rj = d / "results.json"
        if d.is_dir() and rj.is_file():
            doc = json.loads(rj.read_text())
            for key in ("experiment", "title", "provenance", "tables"):
                if key not in doc:
                    env.die(f"{env.rel(rj)}: missing '{key}'")
            if doc["experiment"] != d.name:
                env.die(f"{env.rel(rj)}: experiment '{doc['experiment']}' does not match dir '{d.name}'")
            for key in ("status", "source", "date"):
                if key not in doc["provenance"]:
                    env.die(f"{env.rel(rj)}: provenance missing '{key}'")
            if doc["provenance"]["status"] not in ("measured", "transcribed"):
                env.die(f"{env.rel(rj)}: provenance.status must be measured or transcribed")
            found.append((d, doc))
    found.sort(key=lambda t: int(SECTION_RE.match(t[0].name).group(1)) if SECTION_RE.match(t[0].name) else 999)
    return found


def render_all() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    body = [HEADER]
    for d, doc in experiments():
        body += render_section(d, doc, with_context=True)
        table_md = [
            f"<!-- generated by benchmark/tools/render_report.py from {d.name}/results.json; do not edit -->",
            "",
            *render_section(d, doc, with_context=False),
        ]
        outputs[d / "table.md"] = "\n".join(table_md).rstrip() + "\n"
    outputs[RESULTS_MD] = "\n".join(body).rstrip() + "\n"
    return outputs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if RESULTS.md or any table.md is stale")
    args = ap.parse_args()
    outputs = render_all()
    stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"stale: {env.rel(p)}")
        print("up to date" if not stale else f"{len(stale)} file(s) stale; run benchmark/tools/render_report.py")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text)
        print(f"written: {env.rel(p)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
